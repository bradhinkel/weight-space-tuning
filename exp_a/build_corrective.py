"""A.7 data: the corrective-LoRA training set (run on the pod, GPU).

    python -m exp_a.build_corrective [--n 3000]

- Abstention examples: an xLAM *train* query paired with the tool list of a different xLAM train example,
  chosen so that the two share no function names and no content words between the query and the tools'
  names and descriptions (a crude guarantee that no offered tool fits). The response is generated by the
  *base* model, Qwen/Qwen3.5-2B (self-distillation; greedy, thinking off, same chat template). Only responses
  with no `<tool_call>` / `<function=` that end before the token cap are kept. We over-generate and take
  the first n that pass.
- Call examples: n further xLAM train examples, disjoint from the abstention queries, unchanged.
No practice or test data is used. Output: /workspace/artifacts/a/data/corrective_train.jsonl + corrective_meta.json.
"""
import argparse
import json
import random
import re
import time
from pathlib import Path

import torch

DATA = Path("/workspace/artifacts/a/data")
WORD = re.compile(r"[a-z]{4,}")
STOP = set("""what which where when with that this from have will would could should about into your their there
them they then than been being some more most such only also just like make want need please find give tell
show list using used uses based provide information data value values number numbers name names given each
other between using return returns retrieve fetch fetches specified specific details detail""".split())


def words(s):
    return {w for w in WORD.findall((s or "").lower()) if w not in STOP}


def tool_words(tools):
    out = set()
    for t in tools:
        f = t.get("function", t)
        out |= words(f.get("name", "").replace("_", " ").replace(".", " ")) | words(f.get("description", ""))
    return out


def names(tools):
    return {t.get("function", t).get("name") for t in tools}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--overgen", type=float, default=1.5)
    ap.add_argument("--base", default="Qwen/Qwen3.5-2B")
    ap.add_argument("--max-new", type=int, default=384)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    t0 = time.time()
    rows = [json.loads(l) for l in open(DATA / "xlam_train.jsonl")]
    rng = random.Random(a.seed)
    order = list(range(len(rows))); rng.shuffle(order)
    n_src = int(a.n * a.overgen)
    src_idx, call_idx, tool_pool = order[:n_src], order[n_src:n_src + a.n], order[n_src + a.n:]

    pairs = []
    for i in src_idx:
        r = rows[i]
        q = next(m["content"] for m in r["messages"] if m["role"] == "user")
        qw, qn = words(q), names(r["tools"])
        for _ in range(50):
            t = rows[rng.choice(tool_pool)]["tools"]
            if not (names(t) & qn) and not (tool_words(t) & qw):
                pairs.append({"src_id": r["id"], "messages": [{"role": "user", "content": q}], "tools": t})
                break
    print("pairs", len(pairs), "of", n_src, flush=True)

    from transformers import AutoModelForImageTextToText, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(a.base); tok.padding_side = "left"
    model = AutoModelForImageTextToText.from_pretrained(a.base, dtype=torch.bfloat16, device_map="cuda").eval()
    pad = tok.pad_token_id if tok.pad_token_id is not None else tok.eos_token_id
    stop = sorted({tok.convert_tokens_to_ids(t) for t in ("<|im_end|>", "<|endoftext|>")} - {None})
    ids = [tok(tok.apply_chat_template(p["messages"], tools=p["tools"], tokenize=False, add_generation_prompt=True,
                                       enable_thinking=False), add_special_tokens=False)["input_ids"] for p in pairs]
    outs, finished = [None] * len(ids), [False] * len(ids)
    order2 = sorted(range(len(ids)), key=lambda i: len(ids[i]))
    k, budget = 0, 131072
    with torch.no_grad():
        while k < len(order2):
            n = 1
            while k + n < len(order2) and n < 128 and (n + 1) * (len(ids[order2[k + n]]) + a.max_new) <= budget:
                n += 1
            idx = order2[k:k + n]; k += n
            L = max(len(ids[i]) for i in idx)
            inp = torch.full((len(idx), L), pad, dtype=torch.long); att = torch.zeros_like(inp)
            for r_, i in enumerate(idx):
                inp[r_, L - len(ids[i]):] = torch.tensor(ids[i]); att[r_, L - len(ids[i]):] = 1
            g = model.generate(input_ids=inp.cuda(), attention_mask=att.cuda(), do_sample=False,
                               max_new_tokens=a.max_new, pad_token_id=pad, eos_token_id=stop,
                               temperature=None, top_p=None, top_k=None)
            for r_, i in enumerate(idx):
                new = g[r_, L:].tolist()
                cut = next((j for j, t in enumerate(new) if t in stop), None)
                finished[i] = cut is not None
                outs[i] = tok.decode(new[:cut if cut is not None else len(new)], skip_special_tokens=False)
            print(f"generated {k}/{len(ids)} ({round(time.time() - t0)} s)", flush=True)

    stats = {"pairs": len(pairs), "called": 0, "unfinished": 0, "empty": 0, "kept": 0}
    abst = []
    for p, o, f in zip(pairs, outs, finished):
        text = o.strip()
        if "<tool_call>" in o or "<function=" in o:
            stats["called"] += 1; continue
        if not f:
            stats["unfinished"] += 1; continue
        if "<think>" in text:
            text = text.split("</think>")[-1].strip()
        if not text:
            stats["empty"] += 1; continue
        if len(abst) < a.n:
            abst.append({"id": f"abst_{p['src_id']}", "messages": p["messages"] + [{"role": "assistant", "content": text}],
                         "tools": p["tools"]})
    stats["kept"] = len(abst)
    calls = [rows[i] for i in call_idx]
    mix = abst + calls
    random.Random(a.seed + 1).shuffle(mix)
    with open(DATA / "corrective_train.jsonl", "w") as f:
        for r in mix:
            f.write(json.dumps(r) + "\n")
    meta = {"seed": a.seed, "base": a.base, "n_abstain": len(abst), "n_call": len(calls), "stats": stats,
            "call_ids": [rows[i]["id"] for i in call_idx], "abstain_src_ids": [r["id"] for r in abst],
            "examples": [r["messages"][-1]["content"][:300] for r in abst[:8]], "seconds": round(time.time() - t0)}
    (DATA / "corrective_meta.json").write_text(json.dumps(meta, indent=1))
    print(json.dumps({k: v for k, v in meta.items() if k not in ("call_ids", "abstain_src_ids")}, indent=1))


if __name__ == "__main__":
    main()
